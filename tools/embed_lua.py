#!/usr/bin/env python3
"""Turn runtime/mb_entities.lua into a C header so the device and web builds embed the same Lua."""
import pathlib
root = pathlib.Path(__file__).resolve().parent.parent / 'runtime'
src = (root / 'mb_entities.lua').read_text()
body = ',\n'.join(', '.join(str(b) for b in src.encode()[i:i + 24]) for i in range(0, len(src.encode()), 24))
(root / 'mb_prelude.h').write_text('/* Generated by tools/embed_lua.py from mb_entities.lua. Do not edit. */\n#pragma once\n'
  'static const char mb_prelude_lua[] = {\n' + body + ', 0\n};\n')
print('wrote runtime/mb_prelude.h')
