#!/usr/bin/env python3
"""Turn runtime/bk_lang.lua + bk_entities.lua + bk_game.lua + bk_music.lua into a C header so the device and web builds embed the same Lua."""
import pathlib
root = pathlib.Path(__file__).resolve().parent.parent / 'runtime'
src = (root / 'bk_lang.lua').read_text() + '\n' + (root / 'bk_entities.lua').read_text() + '\n' + (root / 'bk_game.lua').read_text() + '\n' + (root / 'bk_music.lua').read_text()
body = ',\n'.join(', '.join(str(b) for b in src.encode()[i:i + 24]) for i in range(0, len(src.encode()), 24))
(root / 'bk_prelude.h').write_text('/* Generated by tools/embed_lua.py from bk_lang.lua, bk_entities.lua, bk_game.lua and bk_music.lua. Do not edit. */\n#pragma once\n'
  'static const char bk_prelude_lua[] = {\n' + body + ', 0\n};\n')
print('wrote runtime/bk_prelude.h')
